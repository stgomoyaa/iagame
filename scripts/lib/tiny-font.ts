export const GLYPH_W = 5
export const GLYPH_H = 7

/**
 * Dibuja `text` en un buffer RGBA de ancho `stride`, escalado `scale` veces.
 * Pinta también un halo oscuro de 1px escalado, porque el rótulo cae encima
 * de la tesela y sin contraste propio desaparece sobre los camos claros.
 */
export function drawText(
  rgba: Uint8ClampedArray,
  stride: number,
  height: number,
  text: string,
  x0: number,
  y0: number,
  scale: number,
  color: readonly [number, number, number] = [255, 255, 255],
): void {
  const put = (px: number, py: number, c: readonly [number, number, number]): void => {
    if (px < 0 || py < 0 || px >= stride || py >= height) return
    const i = (py * stride + px) * 4
    rgba[i] = c[0]
    rgba[i + 1] = c[1]
    rgba[i + 2] = c[2]
    rgba[i + 3] = 255
  }

  const upper = text.toUpperCase()
  // Dos pasadas: halo primero, glifo después, así el halo nunca tapa el trazo.
  for (const pass of [0, 1]) {
    let cx = x0
    for (const ch of upper) {
      const g = GLYPHS[ch] ?? GLYPHS[' ']
      for (let gy = 0; gy < GLYPH_H; gy++) {
        for (let gx = 0; gx < GLYPH_W; gx++) {
          if (g[gy][gx] !== '1') continue
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const px = cx + gx * scale + sx
              const py = y0 + gy * scale + sy
              if (pass === 0) {
                for (let oy = -scale; oy <= scale; oy++) {
                  for (let ox = -scale; ox <= scale; ox++) put(px + ox, py + oy, [0, 0, 0])
                }
              } else {
                put(px, py, color)
              }
            }
          }
        }
      }
      cx += (GLYPH_W + 1) * scale
    }
  }
}
